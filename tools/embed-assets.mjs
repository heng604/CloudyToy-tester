// Writes server/lib/embedded-assets.gen.ts (logo + mascot as base64) so invoices/e-mails/reports work on Cloudflare Workers, which has no disk.
// Run `npm run embed` again whenever public/img/invoice-logo.jpg or public/img/email/mascot.png changes.
import { readFileSync, writeFileSync } from "node:fs";
const files = ["img/invoice-logo.jpg", "img/email/mascot.png"];
const body = files.map((f) => `  ${JSON.stringify(f)}: "${readFileSync(new URL(`../public/${f}`, import.meta.url)).toString("base64")}",`).join("\n");
writeFileSync(new URL("../server/lib/embedded-assets.gen.ts", import.meta.url), `// GENERATED by tools/embed-assets.mjs - do not edit.\nexport const EMBEDDED: Record<string, string> = {\n${body}\n};\n`);
console.log("embedded", files.length, "files");
